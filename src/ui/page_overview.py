"""Page 1 — Executive Overview."""

from __future__ import annotations

import numpy as np
import pandas as pd
import streamlit as st

from config import settings
from src import customer_metrics, visualizations as viz
from src.ui import components as ui
from src.ui.context import AppContext


def render(ctx: AppContext) -> None:
    summary = ctx.metrics.summary
    orders = ctx.tables["order_values"]
    customers = ctx.metrics.customers

    ui.section_header(
        "Executive overview",
        "What the historical transaction record says about the customer base: how many people bought, "
        "how much value they generated, and how often they came back.",
        eyebrow="Page 1 of 6",
    )

    # ---------------- KPI row ----------------
    cards = [
        ui.kpi_card(
            "Unique eligible customers", ui.fmt_int(summary["n_customers"]),
            f"distinct <code>customer_unique_id</code>",
            "Deduplicated on customer_unique_id, so repeat buyers are not counted twice.",
            "primary",
        ),
        ui.kpi_card(
            "Eligible orders", ui.fmt_int(summary["n_orders"]),
            f"{summary['n_orders_per_customer']:.3f} orders per customer",
            "Order status = delivered, with a valid purchase timestamp.",
            "primary",
        ),
        ui.kpi_card(
            "Repeat-purchase rate", ui.fmt_pct(summary["repeat_purchase_rate"]),
            f"{ui.fmt_int(summary['n_repeat_customers'])} customers with ≥2 orders",
            "Repeat customers ÷ all customers in the eligible population.",
            "teal",
        ),
        ui.kpi_card(
            "Historical merchandise value", ui.fmt_money(summary["merchandise_value"]),
            f"{ui.fmt_money(summary['freight_value'])} freight excluded",
            "Sum of item prices. Revenue-like, not profit.",
            "violet",
        ),
        ui.kpi_card(
            "Average order value", ui.fmt_money(summary["avg_order_value"], digits=2),
            f"median {ui.fmt_money(summary['median_order_value'], digits=2)}",
            "Merchandise value ÷ eligible orders.",
            "amber",
        ),
        ui.kpi_card(
            "Value concentration", ui.fmt_pct(summary.get("top_10pct_share")),
            f"top 10% of customers · Gini {summary['gini_customer_value']:.2f}",
            "Share of historical merchandise value generated by the top 10% of customers.",
            "rose",
        ),
    ]
    ui.kpi_row(cards, per_row=3)

    ui.note(
        f"Observation window <b>{summary['first_order_date']:%d %b %Y}</b> → "
        f"<b>{summary['as_of_date']:%d %b %Y}</b> ({summary['observation_days']:,} days). "
        f"Recency is measured against <b>{summary['as_of_date']:%d %b %Y}</b> — the last day in the "
        f"dataset on which an eligible order was placed — not against today's date."
    )

    # ---------------- Trend ----------------
    ui.section_header(
        "Customer acquisition versus repeat activity",
        "Monthly unique customers split by whether the month was their first eligible purchase.",
        eyebrow="Trend",
    )
    monthly = customer_metrics.monthly_trend(orders)
    split = customer_metrics.monthly_new_vs_returning(orders)
    st.plotly_chart(viz.new_vs_returning(split), width="stretch",
                    config={"displayModeBar": False})

    last = split.iloc[-1]
    recent = split.iloc[-6:]
    ui.callout(
        f"In the most recent complete month shown ({last['month']:%b %Y}), "
        f"<b>{ui.fmt_int(last['new_customers'])}</b> customers bought for the first time and "
        f"<b>{ui.fmt_int(last['returning_customers'])}</b> were returning. Across the last six "
        f"months, returning customers averaged {recent['returning_customers'].mean():,.0f} per month "
        f"against {recent['new_customers'].mean():,.0f} first-time buyers — growth in this window is "
        f"almost entirely acquisition-driven, not repeat-driven.",
        "warning", "Reading the trend",
    )

    col1, col2 = st.columns(2, gap="medium")
    with col1:
        st.plotly_chart(viz.trend_area(monthly, "n_orders", "Eligible orders per month",
                                       "Orders"), width="stretch",
                        config={"displayModeBar": False})
    with col2:
        st.plotly_chart(viz.trend_area(monthly, "avg_order_value", "Average order value per month",
                                       "R$ per order"), width="stretch",
                        config={"displayModeBar": False})

    ui.note(
        "AOV is plotted as a level, not a target: it mixes category mix, freight policy and price "
        "changes, so a rise is not automatically good news."
    )

    # ---------------- Concentration ----------------
    ui.section_header(
        "How concentrated is historical value?",
        "If a small share of customers generates most of the value, retention spend should not be "
        "spread evenly across the base.",
        eyebrow="Concentration",
    )
    col1, col2 = st.columns([1.35, 1], gap="medium")
    with col1:
        st.plotly_chart(viz.concentration_curve(customers), width="stretch",
                        config={"displayModeBar": False})
    with col2:
        deciles = customer_metrics.customer_value_deciles(customers).head(5)
        deciles_display = deciles.rename(columns={
            "value_decile": "Value decile", "n_customers": "Customers",
            "merchandise_value": "Merchandise value", "share_of_value": "Share of value",
            "mean_orders": "Orders / customer",
        })
        st.markdown("**Top 5 deciles by historical value**")
        ui.styled_table(deciles_display, column_config={
            "Merchandise value": st.column_config.NumberColumn(format="%.0f"),
            "Share of value": st.column_config.ProgressColumn(format="%.1f%%", min_value=0,
                                                              max_value=1),
            "Orders / customer": st.column_config.NumberColumn(format="%.2f"),
        })
        ui.note(
            f"Top 1% of customers → {ui.fmt_pct(summary.get('top_1pct_share'))} of value; "
            f"top 20% → {ui.fmt_pct(summary.get('top_20pct_share'))}. The Gini coefficient of "
            f"customer value is {summary['gini_customer_value']:.3f}."
        )

    # ---------------- Key findings ----------------
    ui.section_header("Key retention findings", "Computed from the loaded dataset at run time.",
                      eyebrow="Findings")

    interval_median = summary.get("median_days_to_second_order", float("nan"))
    findings = [
        (
            "Repeat purchasing is rare, not the norm",
            f"Only <b>{ui.fmt_pct(summary['repeat_purchase_rate'])}</b> of "
            f"{ui.fmt_int(summary['n_customers'])} customers placed a second eligible order at any "
            f"point in the window. Any retention strategy has to be built on a very small existing "
            f"base rate, which caps the achievable incremental lift.",
            "warning",
        ),
        (
            "When a customer does repeat, it usually happens quickly",
            f"Median time from first to second order is "
            f"<b>{interval_median:.0f} days</b>; "
            f"{ui.fmt_pct(summary.get('share_gaps_within_30d'))} of observed repeat gaps are within "
            f"30 days and {ui.fmt_pct(summary.get('share_gaps_within_90d'))} within 90 days. "
            f"Re-engagement should therefore be front-loaded, not spread evenly.",
            "insight",
        ),
        (
            "Value concentration is moderate, not extreme",
            f"The top 10% of customers account for "
            f"<b>{ui.fmt_pct(summary.get('top_10pct_share'))}</b> of historical merchandise value and "
            f"the top 20% for <b>{ui.fmt_pct(summary.get('top_20pct_share'))}</b> "
            f"(Gini {summary['gini_customer_value']:.2f}). Value is concentrated, but a large share "
            f"still sits in the long tail of one-time buyers — so a strategy aimed only at the top "
            f"decile would address less than half of historical revenue.",
            "insight",
        ),
        (
            "The recorded measure is revenue-like, not profit",
            f"Total merchandise value of {ui.fmt_money(summary['merchandise_value'])} excludes "
            f"freight ({ui.fmt_money(summary['freight_value'])} recorded separately) and there is no "
            f"cost, margin or campaign data in the source. No profitability conclusion can be drawn.",
            "",
        ),
    ]
    for title, body, kind in findings:
        ui.callout(body, kind or "definition", title)

    # ---------------- Eligibility funnel ----------------
    with st.expander("Order eligibility funnel — why 99,441 rows become "
                     f"{ui.fmt_int(summary['n_orders'])} eligible orders", expanded=False):
        status_counts = pd.DataFrame(
            list(ctx.raw_meta["status_counts"].items()),
            columns=["order_status", "orders"]).sort_values("orders", ascending=False)
        status_counts["share"] = status_counts["orders"] / status_counts["orders"].sum()
        status_counts["eligible"] = np.where(
            status_counts["order_status"].isin(settings.PRIMARY_ELIGIBLE_STATUSES), "Yes", "No")
        col1, col2 = st.columns([1, 1.2], gap="medium")
        with col1:
            ui.styled_table(status_counts.rename(columns={
                "order_status": "Status", "orders": "Orders", "share": "Share", "eligible": "Eligible"}),
                column_config={"Share": st.column_config.ProgressColumn(
                    format="%.1f%%", min_value=0, max_value=1)})
        with col2:
            ui.definition(
                "Why only delivered orders?",
                "A retention KPI should count purchases that actually happened. <code>canceled</code> "
                "and <code>unavailable</code> orders represent no goods received; in-flight statuses "
                "(<code>shipped</code>, <code>processing</code>, …) are only partially observed and "
                "cluster at the end of the window, which would make recent periods look artificially "
                "inactive. The rule is applied identically to every order in every month."
            )
            ui.note("Change <code>PRIMARY_ELIGIBLE_STATUSES</code> in "
                    "<code>config/settings.py</code> to run the sensitivity variant; every page "
                    "recomputes from the same rule.")

    # ---------------- Export ----------------
    with st.expander("Export executive summary (anonymised aggregates)", expanded=False):
        export = pd.DataFrame([{
            "metric": k, "value": v
        } for k, v in summary.items()])
        ui.download_csv(export, "executive_summary.csv")
        ui.note("This export contains aggregates only — no customer-level records.")
